GO

CREATE OR ALTER PROCEDURE PR_I_ALUNO
	@NOME VARCHAR(MAX),
	@EMAIL VARCHAR(MAX),
	@SENHA VARCHAR (MAX),
	@DT_CADASTRO DATETIME2,
	@DT_NASCIMENTO DATETIME2,
	@TELEFONE VARCHAR(MAX) = NULL,
	@OBSERVACAO VARCHAR(MAX) = NULL,
	@ID_NIVEL_APRENDIZADO INT
AS
BEGIN
	DECLARE @ID_OUTPUT INT = 0;

	BEGIN TRY
		BEGIN TRANSACTION;

		INSERT INTO TB_USUARIOS
			(USU_NOME,USU_EMAIL,USU_SENHA,USU_DT_CADASTRO,USU_STATUS)
		VALUES 
			(@NOME, @EMAIL, @SENHA, @DT_CADASTRO, 1);

		SET @ID_OUTPUT = SCOPE_IDENTITY();

		INSERT INTO TB_ALUNOS 
			(ALU_DT_NASCIMENTO, ALU_OBSERVACAO, ALU_TELEFONE, ALU_USU_ID, ALU_NVA_ID)
		VALUES
			(@DT_NASCIMENTO, @OBSERVACAO, @TELEFONE, @ID_OUTPUT, @ID_NIVEL_APRENDIZADO);
		
		COMMIT;
	END TRY

	BEGIN CATCH
		IF @@TRANCOUNT > 0
			ROLLBACK;
		THROW;
	END CATCH;
END


CREATE OR ALTER PROCEDURE PR_I_PROFESSOR
	@NOME VARCHAR(MAX),
	@EMAIL VARCHAR(MAX),
	@SENHA VARCHAR (MAX),
	@DT_CADASTRO DATETIME2,
	@DESCRICAO VARCHAR(MAX),
	@ARRAY_MATERIAS TB_ARRAY_ID_MATERIAS READONLY
AS
BEGIN
	DECLARE @ID_USUARIO_OUT INT = 0;
	DECLARE @ID_PROF_OUT INT = 0;
	
	BEGIN TRY
		BEGIN TRANSACTION;

		--USUARIO
		INSERT INTO TB_USUARIOS
			(USU_NOME,USU_EMAIL,USU_SENHA,USU_DT_CADASTRO,USU_STATUS)
		VALUES 
			(@NOME, @EMAIL, @SENHA, @DT_CADASTRO, 1);

		SET @ID_USUARIO_OUT = SCOPE_IDENTITY();

		--PROFESSOR
		INSERT INTO TB_PROFESSORES 
			(PRF_DESCRICAO,PRF_USU_ID)
		VALUES
			(@DESCRICAO, @ID_USUARIO_OUT);
		SET @ID_PROF_OUT = SCOPE_IDENTITY();

		--MATERIAS-PROFESSOR
		INSERT INTO TB_MATERIAS_PROFESSORES
			(MTPF_PRF_ID, MTPF_MAT_ID)
		SELECT
			@ID_PROF_OUT, ID
		FROM @ARRAY_MATERIAS
		
		COMMIT;
	END TRY

	BEGIN CATCH
		IF @@TRANCOUNT > 0
			ROLLBACK;
		THROW;
	END CATCH;
END


