CREATE OR ALTER PROCEDURE PR_S_ALUNOS_POR_PROF
	@ID_USU INT
AS
BEGIN
	SELECT 
		A.ALU_ID,
		U.USU_NOME,
		U.USU_EMAIL,
		A.ALU_DT_NASCIMENTO,
		A.ALU_OBSERVACAO,
		A.ALU_TELEFONE,
		N.NVA_ID,
		U.USU_STATUS
	FROM TB_ALUNOS A
	JOIN TB_PROFESSORES_ALUNOS PA ON A.ALU_ID = PA.PFAL_ALU_ID
	JOIN TB_PROFESSORES P ON P.PRF_ID = PA.PFAL_PRF_ID
	JOIN TB_USUARIOS U ON A.ALU_USU_ID = USU_ID
	JOIN TB_NIVEIS_APRENDIZADO N ON N.NVA_ID = A.ALU_NVA_ID
	WHERE P.PRF_USU_ID = @ID_USU
END

