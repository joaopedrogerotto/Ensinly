CREATE OR ALTER PROCEDURE PR_S_VALIDAR_LOGIN
	@EMAIL VARCHAR(MAX),
	@SENHA VARCHAR(MAX)
AS
BEGIN
	SELECT
		U.USU_ID,
		U.USU_NOME,
		U.USU_EMAIL,
		CASE
			WHEN A.ALU_ID IS NOT NULL THEN 'ALUNO'
			WHEN P.PRF_ID IS NOT NULL THEN 'PROFESSOR'
			ELSE 'USUARIO'
		END AS TIPO_USUARIO
	FROM TB_USUARIOS U
	LEFT JOIN TB_ALUNOS A ON U.USU_ID = A.ALU_USU_ID
	LEFT JOIN TB_PROFESSORES P ON U.USU_ID = P.PRF_USU_ID
	WHERE
		USU_EMAIL = @EMAIL AND USU_SENHA = @SENHA

END
GO

CREATE OR ALTER PROCEDURE PR_I_USUARIO
